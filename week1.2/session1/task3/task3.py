fruit = ("apple", "banana", "cherry")
print(fruit)

# Find and display position of "banana"
num1 = fruit.index("banana")
print(num1)

# Display how many times "cherry" occurs
num2 = fruit.count("cherry")
print(num2)

# Display how many times "strawberry" occurs
num2 = fruit.count("strawberry")
print(num2)

# Unpack tuple into variables
(first, second, third) = fruit
print(first)
print(second)
print(third)
